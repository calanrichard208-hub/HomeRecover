const DICTS = { en, ta, hi };

export function translate(lang, key, vars = {}) {
  const raw = (DICTS[lang] && DICTS[lang][key]) ?? en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? String(vars[k]) : `{${k}}`));
}

